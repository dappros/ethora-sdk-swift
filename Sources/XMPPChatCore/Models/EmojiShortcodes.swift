//  Reaction shortcode table. The wire carries shortcodes ("+1", "heart",
//  "joy") and every client renders the native glyph. The rows are generated
//  from the web SDK's emoji data (@emoji-mart/data, sets/15/native.json) so
//  the Swift picker offers the same ids the web picker sends.
