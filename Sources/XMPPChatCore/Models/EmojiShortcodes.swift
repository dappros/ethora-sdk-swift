import Foundation

public enum EmojiShortcodes {
    /// Quick-reaction bar default. Same ids as the RN SDK's
    /// `DEFAULT_QUICK_REACTIONS` (config key `reactions.quickReactions`).
    public static let defaultQuickReactions: [String] = [
        "+1", "heart", "joy", "open_mouth", "cry", "pray"
    ]

    /// One picker entry: shortcode, native glyph and emoji-mart category id.
    public struct Entry: Equatable {
        public let shortcode: String
        public let glyph: String
        public let category: String
    }

    /// Category ids in picker order.
    public static let categoryOrder: [String] = [
        "people", "nature", "foods", "activity", "places", "objects", "symbols", "flags"
    ]

    /// Every entry, grouped by category in `categoryOrder`.
    public static let entries: [Entry] = rows.map { Entry(shortcode: $0.0, glyph: $0.1, category: $0.2) }

    /// Entries of one category, in table order.
    public static func entries(in category: String) -> [Entry] {
        entries.filter { $0.category == category }
    }

    /// Native glyph for a shortcode, or nil when the shortcode is unknown.
    /// Unknown shortcodes are still stored and sent; the UI shows the raw text.
    public static func glyph(for shortcode: String) -> String? {
        glyphByShortcode[shortcode]
    }

    private static let glyphByShortcode: [String: String] = {
        var map: [String: String] = [:]
        map.reserveCapacity(rows.count)
        for row in rows where map[row.0] == nil {
            map[row.0] = row.1
        }
        return map
    }()

